#!/usr/bin/env python3
"""
src/ 配下の ES Modules から、file:// プロトコル直接起動用の
単一バンドル dist/app.bundle.js を生成するスクリプト。
外部ツールに依存せず Python 標準ライブラリのみで動作する。
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "src"
ENTRY = SRC_DIR / "main.js"
OUT_FILE = ROOT / "dist" / "app.bundle.js"

IMPORT_RE = re.compile(
    r"^\s*import\s*\{([^}]+)\}\s*from\s*['\"]([^'\"]+)['\"]\s*;?",
    re.MULTILINE | re.DOTALL,
)


def resolve_import(current_file: Path, rel_spec: str) -> Path:
    return (current_file.parent / rel_spec).resolve()


def collect_modules(entry: Path) -> list[Path]:
    visited = set()
    ordered = []

    def dfs(path: Path):
        if path in visited:
            return
        visited.add(path)
        text = path.read_text(encoding="utf-8")
        for m in IMPORT_RE.finditer(text):
            dep = resolve_import(path, m.group(2))
            if dep.exists():
                dfs(dep)
        ordered.append(path)

    dfs(entry.resolve())
    return ordered


def transform_module(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    exported_names: list[str] = []

    def replace_import(m: re.Match) -> str:
        spec_list = m.group(1)
        rel_path = m.group(2)
        dep_path = resolve_import(path, rel_path).relative_to(ROOT).as_posix()
        bindings = []
        for raw_item in spec_list.split(","):
            item = raw_item.strip()
            if not item:
                continue
            if " as " in item:
                orig, alias = [p.strip() for p in item.split(" as ", 1)]
                bindings.append(f"{orig}: {alias}")
            else:
                bindings.append(item)
        return f"const {{ {', '.join(bindings)} }} = __require('{dep_path}');"

    text = IMPORT_RE.sub(replace_import, text)

    def replace_export_decl(m: re.Match) -> str:
        kind = m.group(1)
        name = m.group(2)
        exported_names.append(name)
        return f"{kind} {name}"

    text = re.sub(
        r"^export\s+(const|let|var|function|class)\s+([A-Za-z_$][A-Za-z0-9_$]*)",
        replace_export_decl,
        text,
        flags=re.MULTILINE,
    )

    if exported_names:
        exports_stmt = "\n" + "\n".join(
            f"__exports.{name} = {name};" for name in exported_names
        )
        text = text + exports_stmt

    return text


def build():
    modules = collect_modules(ENTRY)
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    parts = [
        "// Auto-generated by scripts/build_bundle.py for file:// protocol compatibility.\n",
        "(function () {\n",
        "  'use strict';\n",
        "  const __factories = {};\n",
        "  const __cache = {};\n",
        "  function __define(id, fn) { __factories[id] = fn; }\n",
        "  function __require(id) {\n",
        "    if (__cache[id]) return __cache[id].exports;\n",
        "    const mod = { exports: {} };\n",
        "    __cache[id] = mod;\n",
        "    __factories[id](mod.exports, __require);\n",
        "    return mod.exports;\n",
        "  }\n\n",
    ]

    for mod_path in modules:
        rel = mod_path.relative_to(ROOT).as_posix()
        transformed = transform_module(mod_path)
        indented = "\n".join("    " + line if line else "" for line in transformed.splitlines())
        parts.append(f"  __define('{rel}', function (__exports, __require) {{\n{indented}\n  }});\n\n")

    entry_rel = ENTRY.relative_to(ROOT).as_posix()
    parts.append(f"  __require('{entry_rel}');\n")
    parts.append("})();\n")

    OUT_FILE.write_text("".join(parts), encoding="utf-8")
    print(f"Built {OUT_FILE} ({len(modules)} modules)")


if __name__ == "__main__":
    build()
